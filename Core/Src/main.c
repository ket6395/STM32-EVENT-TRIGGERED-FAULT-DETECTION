/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_ADC1_Init();
  MX_TIM2_Init();
  MX_USART2_UART_Init();
  /* USER CODE BEGIN 2 */

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
 while (1)
{
    HAL_ADC_Start(&hadc1);

    HAL_ADC_PollForConversion(&hadc1, HAL_MAX_DELAY);

    adc_raw = HAL_ADC_GetValue(&hadc1);

    voltage = (adc_raw * 3.3f) / 4095.0f;

    temperature =
    ((voltage - 0.76f) / 0.0025f) + 25.0f;

    /* Fault Injection */

    if(total_samples > 50 && total_samples < 100)
    {
        temperature += 5;
    }

    if(total_samples > 150 && total_samples < 200)
    {
        temperature += 10;
    }

    if(total_samples > 250 && total_samples < 300)
    {
        temperature += 15;
    }

    /* Labels */

    if(temperature < 45)
    {
        label = 0;
    }
    else if(temperature < 50)
    {
        label = 1;
    }
    else
    {
        label = 2;
    }

    /* Circular Buffer */

    temp_buffer[buf_index] = temperature;

    buf_index++;

    if(buf_index >= 10)
    {
        buf_index = 0;
    }

    total_samples++;
    window_samples++;

    /* Delta T */

    deltaT = temperature - prev_temp;

    if(deltaT < 0)
    {
        deltaT = -deltaT;
    }

    /* Moving Average */

    float sum = 0;

    for(int i=0;i<10;i++)
    {
        sum += temp_buffer[i];
    }

    moving_avg = sum / 10.0f;

    /* Variance */

    float var = 0;

    for(int i=0;i<10;i++)
    {
        float diff =
        temp_buffer[i] - moving_avg;

        var += diff * diff;
    }

    variance = var / 10.0f;

    /* Event Trigger */

    if(deltaT > threshold)
    {
        event_count++;
        window_events++;

        prev_temp = temperature;
    }

    /* Overall CPU Reduction */

    if(total_samples > 0)
    {
        cpu_reduction =
        100.0f *
        (1.0f -
        ((float)event_count /
         (float)total_samples));
    }

    /* Fixed Window CPU Reduction */

    if(window_samples >= 100)
    {
        window_cpu_reduction =
        100.0f *
        (1.0f -
        ((float)window_events /
         (float)window_samples));

        window_samples = 0;
        window_events = 0;
    }

    /* Event Rate */

    event_rate =
    100.0f *
    ((float)event_count /
     (float)total_samples);

    /* State Machine */

    if(deltaT < 2.0)
    {
        system_state = NORMAL;
    }
    else if(deltaT < 5.0)
    {
        system_state = WARNING;
    }
    else
    {
        system_state = FAULT;

        fault_count++;
    }

    /* LED Control */

    HAL_GPIO_WritePin(GPIOA,
                      GPIO_PIN_5 |
                      GPIO_PIN_6 |
                      GPIO_PIN_7,
                      GPIO_PIN_RESET);

    switch(system_state)
    {
        case NORMAL:

            HAL_GPIO_WritePin(GPIOA,
                              GPIO_PIN_5,
                              GPIO_PIN_SET);
            break;

        case WARNING:

            HAL_GPIO_WritePin(GPIOA,
                              GPIO_PIN_6,
                              GPIO_PIN_SET);
            break;

        case FAULT:

            HAL_GPIO_WritePin(GPIOA,
                              GPIO_PIN_7,
                              GPIO_PIN_SET);
            break;
    }

    /* UART Logging */

    sprintf(msg,
    "T=%.2f DT=%.2f AVG=%.2f VAR=%.2f CPU=%.1f EVT=%.1f STATE=%u FAULTS=%lu\r\n",
    temperature,
    deltaT,
    moving_avg,
    variance,
    window_cpu_reduction,
    event_rate,
    system_state,
    fault_count);

    HAL_UART_Transmit(&huart2,
                      (uint8_t*)msg,
                      strlen(msg),
                      HAL_MAX_DELAY);

    HAL_Delay(1000);

}
}
